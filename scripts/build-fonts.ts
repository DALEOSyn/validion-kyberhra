/**
 * Writes src/styles/fonts.css from the @fontsource packages: only the latin and latin-ext subsets (Slovak) of the
 * weights the game uses, woff2 only (every supported browser reads it), with unicode-range so a browser
 * downloads only what a page needs. Fonts are bundled locally: no font CDN at runtime.
 * Run after changing fonts: npx tsx scripts/build-fonts.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const FONTS: [pkg: string, weights: number[]][] = [
  ['baloo-2', [800]],
  ['nunito', [400, 700, 800]],
  ['special-elite', [400]],
];

const out: string[] = ['/* Generated by scripts/build-fonts.ts. Do not edit by hand. Fonts: SIL Open Font License 1.1. */'];
for (const [pkg, weights] of FONTS) {
  for (const w of weights) {
    const css = readFileSync(resolve(root, `node_modules/@fontsource/${pkg}/${w}.css`), 'utf8');
    for (const block of css.split('/* ').slice(1)) {
      const name = block.slice(0, block.indexOf(' */'));
      if (!/-(latin|latin-ext)-\d+-normal$/.test(name)) continue;
      const body = block
        .slice(block.indexOf('@font-face'))
        .replace(/url\(\.\/files\/([^)]+)\.woff2\) format\('woff2'\), url\(\.\/files\/[^)]+\.woff\) format\('woff'\)/, `url('@fontsource/${pkg}/files/$1.woff2') format('woff2')`)
        .trim();
      out.push(`/* ${name} */\n${body}`);
    }
  }
}
writeFileSync(resolve(root, 'src/styles/fonts.css'), out.join('\n\n') + '\n');
